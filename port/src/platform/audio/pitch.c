s32 pitch_bend_of(int wheel14, int scale)
{
    return (s32)((wheel14 - 0x2000) >> 5) * scale;
}

void pitch_lookup(int index, s32 bend, u8 *a0, u8 *b0)
{
    s32 bx = (s32)index - 0x18;
    s32 ax;
    int idx2, sem, oct, block;
    s16 v;

    /* PORT: 0x3630-0x3639, a mandatory first add (do/while), then the
     * 0x363b-0x3644 wrap; this folds the index by -12 for the octave tables. */
    do {
        bx += 0xc;
    } while (bx < 0);
    while (bx > 0x5f)
        bx -= 0xc;

    /* PORT: 0x3646-0x3664. The 0xc0 fold is not a clamp: a bent wheel that
     * crosses an octave boundary wraps, it does not saturate. */
    ax = (bend + (bx << 8) + 8) >> 4;
    while (ax < 0)
        ax += 0xc0;
    while (ax > 0x5ff)
        ax -= 0xc0;

    idx2 = (int)(ax >> 4);
    sem = T9DD[idx2];
    oct = T97D[idx2];
    /* PORT: 0x367c-0x3683 addresses the table in bytes: word step ax & 0xf. */
    v = PITCH_TBL[16 * sem + ((int)ax & 0xf)];
    block = oct - 1 + (v < 0);
    if (block < 0) {
        block++;
        v = (s16)(v >> 1);
    }
    *a0 = (u8)(v & 0xff);
    *b0 = (u8)((block << 2) | ((v >> 8) & 0x03));
}
